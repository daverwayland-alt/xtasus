function shuffle(array) {
  let currentIndex = array.length,
    randomIndex;
  while (currentIndex != 0) {
    randomIndex = Math.floor(Math.random() * currentIndex);
    currentIndex--;
    [array[currentIndex], array[randomIndex]] = [array[randomIndex], array[currentIndex]];
  }
  return array;
}

export const getRandomCard = (level, type, players, currentPlayer, playedCardIds = [], customCards = []) => {
  const typeMatch = c => !type || type === 'random' || c.type === type;
  const notPlayed = c => !playedCardIds.includes(c.id);

  const allCards = [...cards, ...customCards.map(c => ({ ...c, level }))];

  let pool = allCards.filter(c => c.level === level && typeMatch(c) && notPlayed(c));

  if (pool.length === 0) {
    pool = allCards.filter(c => typeMatch(c) && notPlayed(c));
  }

  if (pool.length === 0) {
    pool = allCards.filter(c => c.level === level && typeMatch(c));
  }

  if (pool.length === 0) {
    return { id: `error_${Date.now()}`, type: type === 'truth' ? 'truth' : 'dare', level, text: '¡Se agotaron todas las cartas! Suban de nivel.' };
  }

  const card = pool[Math.floor(Math.random() * pool.length)];

  let text = card.text;
  const otherPlayers = shuffle(players.filter(p => p !== currentPlayer));

  if (text.includes('{player1}')) {
    text = text.replace(/{player1}/g, otherPlayers[0] ?? 'Jugador de la derecha');
  }
  if (text.includes('{player2}')) {
    text = text.replace(/{player2}/g, otherPlayers[1] ?? otherPlayers[0] ?? 'Jugador de la izquierda');
  }

  return { ...card, text };
};
